-- 001_create_fleettrack_tables.sql
-- FleetTrack - Vehicle Fleet, Maintenance, and Operations Management System
-- Built from the FleetTrack ERD (17 tables). Run on fleettrack_db after 000_drop_warehouse_tables.sql.
--
-- Only rules drawn in the ERD are included: primary keys, foreign keys, nullable FKs
-- (fuel_record.trip_id, audit_log.user_id) and the 1 : 0..1 links from EMPLOYEE
-- (enforced with UNIQUE on employee_id). ON DELETE is not defined in the ERD, so PostgreSQL's
-- default (NO ACTION = parent delete is rejected while children exist) applies.
-- Extra rules (UNIQUE username/plate_number, CHECK on stock, etc.) are listed at the bottom
-- as SUGGESTIONS for the team to approve. They are NOT applied.

BEGIN;

CREATE TABLE role (
    role_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name    VARCHAR(50) NOT NULL,
    description  TEXT
);

CREATE TABLE branch (
    branch_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_name     VARCHAR(100) NOT NULL,
    address         VARCHAR(255),
    city            VARCHAR(100),
    contact_number  VARCHAR(30),
    branch_status   VARCHAR(30),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE employee (
    employee_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id          INTEGER NOT NULL REFERENCES branch (branch_id),
    first_name         VARCHAR(100) NOT NULL,
    last_name          VARCHAR(100) NOT NULL,
    contact_number     VARCHAR(30),
    email              VARCHAR(150),
    employment_status  VARCHAR(30),
    created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_account (
    user_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     INTEGER NOT NULL UNIQUE REFERENCES employee (employee_id),  -- EMPLOYEE 1 : 0..1
    role_id         INTEGER NOT NULL REFERENCES role (role_id),
    username        VARCHAR(50) NOT NULL,
    password_hash   VARCHAR(255) NOT NULL,
    account_status  VARCHAR(30),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP
);

CREATE TABLE driver (
    driver_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     INTEGER NOT NULL UNIQUE REFERENCES employee (employee_id),  -- EMPLOYEE 1 : 0..1
    license_number  VARCHAR(50) NOT NULL,
    license_expiry  DATE
);

CREATE TABLE technician (
    technician_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     INTEGER NOT NULL UNIQUE REFERENCES employee (employee_id),  -- EMPLOYEE 1 : 0..1
    specialization  VARCHAR(100)
);

CREATE TABLE vehicle_type (
    vehicle_type_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name          VARCHAR(50) NOT NULL,
    description        TEXT,
    fuel_type          VARCHAR(30),
    standard_capacity  NUMERIC(10,2)
);

CREATE TABLE vehicle (
    vehicle_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type_id  INTEGER NOT NULL REFERENCES vehicle_type (vehicle_type_id),
    branch_id        INTEGER NOT NULL REFERENCES branch (branch_id),
    plate_number     VARCHAR(20) NOT NULL,
    make             VARCHAR(50),
    model            VARCHAR(50),
    year_acquired    INTEGER,
    current_mileage  NUMERIC(10,1),
    vehicle_status   VARCHAR(30),
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP
);

CREATE TABLE vehicle_assignment (
    assignment_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id         INTEGER NOT NULL REFERENCES vehicle (vehicle_id),
    driver_id          INTEGER NOT NULL REFERENCES driver (driver_id),
    assigned_from      DATE NOT NULL,
    assigned_until     DATE,
    assignment_status  VARCHAR(30),
    assignment_notes   TEXT
);

CREATE TABLE trip (
    trip_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id        INTEGER NOT NULL REFERENCES vehicle (vehicle_id),
    driver_id         INTEGER NOT NULL REFERENCES driver (driver_id),
    branch_id         INTEGER NOT NULL REFERENCES branch (branch_id),
    trip_date         DATE NOT NULL,
    origin            VARCHAR(150),
    destination       VARCHAR(150),
    starting_mileage  NUMERIC(10,1),
    ending_mileage    NUMERIC(10,1),
    trip_status       VARCHAR(30),
    purpose           VARCHAR(255),
    created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE fuel_record (
    fuel_record_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id        INTEGER NOT NULL REFERENCES vehicle (vehicle_id),
    trip_id           INTEGER REFERENCES trip (trip_id),   -- nullable per ERD
    fuel_date         DATE NOT NULL,
    liters            NUMERIC(10,2),
    price_per_liter   NUMERIC(10,2),
    total_cost        NUMERIC(12,2),
    odometer_reading  NUMERIC(10,1),
    fuel_station      VARCHAR(100),
    created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE inspection (
    inspection_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id        INTEGER NOT NULL REFERENCES vehicle (vehicle_id),
    user_id           INTEGER NOT NULL REFERENCES user_account (user_id),
    inspection_date   DATE NOT NULL,
    odometer_reading  NUMERIC(10,1),
    inspection_type   VARCHAR(50),
    result            VARCHAR(30),
    remarks           TEXT,
    created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE maintenance (
    maintenance_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id        INTEGER NOT NULL REFERENCES vehicle (vehicle_id),
    technician_id     INTEGER NOT NULL REFERENCES technician (technician_id),
    maintenance_date  DATE NOT NULL,
    maintenance_type  VARCHAR(50),
    description       TEXT,
    status            VARCHAR(30),
    labor_cost        NUMERIC(12,2),
    total_cost        NUMERIC(12,2),
    completed_at      TIMESTAMP
);

CREATE TABLE part (
    part_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_name       VARCHAR(100) NOT NULL,
    part_number     VARCHAR(50),
    category        VARCHAR(50),
    unit_cost       NUMERIC(12,2),
    stock_quantity  INTEGER,
    reorder_level   INTEGER,
    part_status     VARCHAR(30)
);

CREATE TABLE maintenance_part (
    maintenance_id  INTEGER NOT NULL REFERENCES maintenance (maintenance_id),
    part_id         INTEGER NOT NULL REFERENCES part (part_id),
    quantity_used   INTEGER NOT NULL,
    unit_cost       NUMERIC(12,2),
    total_cost      NUMERIC(12,2),
    PRIMARY KEY (maintenance_id, part_id)
);

CREATE TABLE vehicle_status_history (
    status_history_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id         INTEGER NOT NULL REFERENCES vehicle (vehicle_id),
    user_id            INTEGER NOT NULL REFERENCES user_account (user_id),
    previous_status    VARCHAR(30),
    new_status         VARCHAR(30) NOT NULL,
    changed_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reason             TEXT
);

CREATE TABLE audit_log (
    audit_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER REFERENCES user_account (user_id),   -- nullable per ERD
    table_name        VARCHAR(100) NOT NULL,
    record_id         INTEGER,
    action_type       VARCHAR(20) NOT NULL,
    old_values        TEXT,
    new_values        TEXT,
    action_timestamp  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;

